#!/usr/bin/env python3
"""Build station-screen/data/gtfs.js from Metrolink's official static GTFS.

    python3 station-screen/tools/build-gtfs.py            # downloads the current feed
    python3 station-screen/tools/build-gtfs.py gtfs.zip   # or uses a local copy

Metrolink republishes the feed ~5x a year (https://metrolinktrains.com/about/gtfs/); rerun after each change.
Output is a classic script (window.GTFS = ...) so the screen also works from file:// and GitHub Pages.
"""
import csv, io, json, sys, urllib.request, zipfile, pathlib, datetime

SRC = 'https://metrolinktrains.com/globalassets/about/gtfs/gtfs.zip'
OUT = pathlib.Path(__file__).resolve().parent.parent / 'data' / 'gtfs.js'
# Poster ids/names for GTFS route_ids (the ids the existing poster already uses).
LINE = {
    'Antelope Valley Line': ('AVL', 'Antelope Valley Line'),
    'San Bernardino Line': ('SBL', 'San Bernardino Line'),
    'Ventura County Line': ('VCL', 'Ventura County Line'),
    'Orange County Line': ('OCL', 'Orange County Line'),
    'Riverside Line': ('RIV', 'Riverside Line'),
    '91 Line': ('91PV', '91/Perris Valley Line'),
    'Inland Emp.-Orange Co. Line': ('IEOC', 'Inland Empire-Orange County Line'),
}

raw = open(sys.argv[1], 'rb').read() if len(sys.argv) > 1 else urllib.request.urlopen(SRC, timeout=60).read()
z = zipfile.ZipFile(io.BytesIO(raw))
read = lambda n: list(csv.DictReader(io.TextIOWrapper(z.open(n), 'utf-8-sig')))
def hms(s):  # minutes after service-day midnight; can pass 1440
    h, m, x = map(int, s.split(':')); v = h * 60 + m + x / 60
    return int(v) if v.is_integer() else round(v, 2)

stops_raw = read('stops.txt')
stop_ix = {s['stop_id']: i for i, s in enumerate(stops_raw)}
stops = [[s['stop_name'], round(float(s['stop_lat']), 6), round(float(s['stop_lon']), 6), s['stop_id']] for s in stops_raw]

routes_raw = read('routes.txt')
route_ix = {r['route_id']: i for i, r in enumerate(routes_raw)}
routes = [{'gtfs': r['route_id'], 'id': LINE[r['route_id']][0], 'name': LINE[r['route_id']][1],
           'color': '#' + r['route_color'], 'url': r['route_url']} for r in routes_raw]

services = {}
for c in read('calendar.txt'):
    services[c['service_id']] = {'days': [int(c[d]) for d in ('monday', 'tuesday', 'wednesday', 'thursday', 'friday', 'saturday', 'sunday')],
                                 'start': c['start_date'], 'end': c['end_date'], 'add': [], 'remove': []}
for c in read('calendar_dates.txt'):
    s = services.setdefault(c['service_id'], {'days': [0] * 7, 'start': '', 'end': '', 'add': [], 'remove': []})
    s['add' if c['exception_type'] == '1' else 'remove'].append(c['date'])

st = {}
for r in read('stop_times.txt'):
    st.setdefault(r['trip_id'], []).append((int(r['stop_sequence']), stop_ix[r['stop_id']], hms(r['arrival_time']), hms(r['departure_time'])))

trips = []
for t in read('trips.txt'):
    if t['trip_id'] not in st: continue
    seq = sorted(st[t['trip_id']])
    assert all(a[2] <= a[3] for a in seq) and all(seq[i][3] <= seq[i + 1][2] for i in range(len(seq) - 1)), t['trip_id']
    trips.append([route_ix[t['route_id']], t['service_id'], t['trip_id'], t['trip_short_name'], t['trip_headsign'], int(t['direction_id']),
                  [s[1] for s in seq], [s[2] for s in seq], [s[3] for s in seq], [s[0] for s in seq]])

# Poster order per line: merge every stop pattern into one sequence, oriented like the poster (L.A. last; IEOC from San Bernardino).
LA = next(i for i, s in enumerate(stops) if s[0] == 'L.A. Union Station')
for ri, r in enumerate(routes):
    pats = [t[6] if t[5] == 0 else t[6][::-1] for t in trips if t[0] == ri]
    order = list(max(pats, key=len))
    for p in sorted(pats, key=len, reverse=True):
        for k, s in enumerate(p):
            if s in order: continue
            if k and p[k - 1] in order: order.insert(order.index(p[k - 1]) + 1, s)
            elif k + 1 < len(p) and p[k + 1] in order: order.insert(order.index(p[k + 1]), s)
    assert len(order) == len(set(order)) and all(s in order for p in pats for s in p), r['id']
    r['stops'] = order[::-1] if order[0] == LA else order

info = read('feed_info.txt')[0]
data = {'version': info['feed_version'], 'built': datetime.date.today().isoformat(), 'source': SRC,
        'stops': stops, 'routes': routes, 'services': services, 'trips': trips}
OUT.parent.mkdir(exist_ok=True)
OUT.write_text('// Generated by tools/build-gtfs.py from Metrolink official static GTFS. Do not edit by hand.\n'
               'window.GTFS = ' + json.dumps(data, separators=(',', ':')) + ';\n')
print(f'{OUT}: {len(trips)} trips, {len(stops)} stops, feed {info["feed_version"]}, {OUT.stat().st_size // 1024} KB')
for r in routes: print(' ', r['id'], ' > '.join(stops[s][0] for s in r['stops']))
